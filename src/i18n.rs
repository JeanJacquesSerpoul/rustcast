pub fn tr(lang: Lang, key: &'static str) -> &'static str {
    STRINGS
        .iter()
        .find(|(k, _, _)| *k == key)
        .map(|(_, fr, en)| match lang {
            Lang::Fr => *fr,
            Lang::En => *en,
        })
        .unwrap_or(key)
}
